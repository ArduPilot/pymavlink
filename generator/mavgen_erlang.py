from __future__ import print_function
import os
import math

from . import mavparse

try:
    math.log2(2)

    def is_position(val):
        return math.log2(val).is_integer()
except:
    def is_position(val):
        return 2 ** int(math.log(val, 2)) == val

class Type():
  def __init__(self, signed, erl_type, unit=8):
    self.signed = signed
    self.erl_type = erl_type
    self.unit = unit

types = {
  'uint8_t' : Type(signed="unsigned-", erl_type='integer', unit=8),
  'uint16_t' : Type(signed="unsigned-", erl_type='integer', unit=16),
  'uint32_t' : Type(signed="unsigned-", erl_type='integer', unit=32),
  'uint64_t' : Type(signed="unsigned-", erl_type='integer', unit=64),
  'int8_t' : Type(signed="signed-", erl_type='integer', unit=8),
  'int16_t' : Type(signed="signed-", erl_type='integer', unit=16),
  'int32_t' : Type(signed="signed-", erl_type='integer', unit=32),
  'int64_t' : Type(signed="signed-", erl_type='integer', unit=64),
  'float' : Type(signed="signed-", erl_type='float', unit=32),
  'char' : Type(signed="", erl_type='binary', unit=8)}

bitmasks = {}


def hrl_header():
  return """\
%%%-------------------------------------------------------------------
%% generated by mavgen_erlang
%% Fil Andrii 2026
%%%-------------------------------------------------------------------

-type uint8_t() :: 0..16#ff.
-type uint16_t() :: 0..16#ffff.
-type uint32_t() :: 0..16#ffffffff.
-type uint64_t() :: 0..16#ffffffffffffffff.
-type int8_t() :: -128..127.
-type int16_t() :: -32768..32767.
-type int32_t() :: -2147483648..2147483647.
-type int64_t() :: -9223372036854775808..9223372036854775807.

-record (msg_info, {seq, sys_id, comp_id}).

-record (mavlink_connection, {system_id,
  component_id = 1 :: uint8_t(),
  sequence = 0 :: uint8_t()}).\n"""

def erl_header():
  return """\
%%%-------------------------------------------------------------------
%% generated by mavgen_erlang
%% Fil Andrii 2026
%%%-------------------------------------------------------------------

-module(mavlink).

-export([decode/1, encode/2, to_proplist/1]).

-include("mavlink.hrl").

x25crc_update(Checksum, Data) ->
  Tmp0 = Data bxor (Checksum band 16#FF),
  Tmp = (Tmp0 bxor (Tmp0 bsl 4)) band 16#FF,
  (Checksum bsr 8) bxor (Tmp bsl 8) bxor (Tmp bsl 3) bxor (Tmp bsr 4).

x25crc_calculate(Checksum, <<>>, CRC_Extra) ->
  x25crc_update(Checksum, CRC_Extra);

x25crc_calculate(Checksum, <<Data:8, Other_Data/binary>>, CRC_Extra) ->
  x25crc_calculate(x25crc_update(Checksum, Data), Other_Data, CRC_Extra).

x25crc_calculate(Data, CRC_Extra) ->
  x25crc_calculate(16#FFFF, Data, CRC_Extra).

decode(<<16#fe:8, Len:8, Header:4/binary-unit:8, Payload:Len/binary-unit:8, Checksum:2/little-unsigned-integer-unit:8, Other0/binary>>) ->
  {Msgs, Other} = decode(Other0),

  <<Seq:8, SysId:8, CompId:8, MsgId:8>> = Header,
  Calculated_Checksum = case crc_extra(MsgId) of
    unknown -> unknown_msg_id;
    CRC_Extra ->
      x25crc_calculate(<<Len:1/unsigned-integer-unit:8, Header:4/binary-unit:8, Payload:Len/binary-unit:8>>, CRC_Extra)
  end,

  Msg = case Calculated_Checksum of
    Checksum -> {#msg_info{seq = Seq, sys_id = SysId, comp_id = CompId}, message(MsgId, Payload)};
    _ -> bad_checksum
  end,

  {lists:append([Msg], Msgs), Other};

decode(<<>>) ->
  {[], <<>>};

decode(Data0) ->
  case Data0 of
    <<16#fe:8, _D/binary>> -> {[], Data0};
    <<_:8, Data/binary>> -> decode(Data)
  end.

encode(Conn0, Msg) ->
  {MsgId, Payload, CRC_Extra} = encode(Msg),
  Len = byte_size(Payload),
  Seq = Conn0#mavlink_connection.sequence,
  Sys_id = Conn0#mavlink_connection.system_id,
  Comp_id = Conn0#mavlink_connection.component_id,
  Data = <<Len:8, Seq:8,
     Sys_id:8,
     Comp_id:8,
     MsgId:8,
     Payload:Len/binary-unit:8>>,
  Checksum = x25crc_calculate(Data, CRC_Extra),
  {Conn0#mavlink_connection{sequence = (Conn0#mavlink_connection.sequence + 1) rem 256},
   <<16#fe:8, Data/binary, Checksum:2/little-unsigned-integer-unit:8>>}.

to_int(B) ->
  if B ->
    1;
  true ->
    0
  end.

to_string(S, Num) 
    when byte_size(S) >= Num ->
  S;

to_string(S, Num) ->
  to_string(<<S/binary, 0>>, Num).

trim(<<0:8, _Other/binary>>, S) ->
  S;

trim(<<C:1/binary, Other/binary>>, S) ->
  trim(Other, <<S/binary, C/binary>>);

trim(<<>>, S) ->
  S.

pack_binary(_Type, _Size, [], Res) ->
  Res;

pack_binary(float, Size, [F | Other], Res) ->
  pack_binary(float, Size, Other, <<Res/binary, F:Size/little-signed-float-unit:1>>);

pack_binary(integer, Size, [F | Other], Res) ->
  pack_binary(integer, Size, Other, <<Res/binary, F:Size/little-signed-integer-unit:1>>);

pack_binary(uint, Size, [F | Other], Res) ->
  pack_binary(integer, Size, Other, <<Res/binary, F:Size/little-unsigned-integer-unit:1>>).

pack_binary(Type, Size, FL) ->
  pack_binary(Type, Size, FL, <<>>).

unpack_binary(_Type, _Size, <<>>, Res) ->
  Res;

unpack_binary(float, Size, <<0, 0, 192, 127, Other/binary>>, Res) ->
  unpack_binary(float, Size, Other, Res ++ [nan]);

unpack_binary(float, Size, B, Res) ->
  <<F:Size/little-signed-float-unit:1, Other/binary>> = B,
  unpack_binary(float, Size, Other, Res ++ [F]);

unpack_binary(integer, Size, B, Res) ->
  <<F:Size/little-signed-integer-unit:1, Other/binary>> = B,
  unpack_binary(integer, Size, Other, Res ++ [F]).

unpack_binary(Type, Size, B) ->
  unpack_binary(Type, Size, B, []).\n"""

def crc_extra_footer():
  return """
crc_extra(_) -> unknown.\n"""

def decode_footer():
  return """
message(_, <<_Data/binary>>) ->
  unknown.\n"""

def encode_footer():
  return """
encode(_) ->
  <<>>.\n"""

def to_proplists_footer():
  return """
to_proplist(_) ->
  []."""


def atom_repr(s):
  if s[0] < 'a' or s[0] > 'z' or s == "end":
    return "'" + s + "'"
  return s


def get_common_prefix(l):
  common_prefix = l[0].name
  for e in l[1:]:
    if e.end_marker:
      continue
    while not e.name.startswith(common_prefix):
      common_prefix_list = common_prefix.rstrip('_').rsplit('_', 1)
      if len(common_prefix_list) == 1:
        return ""
      common_prefix = common_prefix_list[0]
  return common_prefix


def get_len_common_prefix_of_element(e):
  if not len(e.entry):
    raise ValueError("Erase element " + e.name)
  return len(get_common_prefix([e] + e.entry))


def generate_bitmask(bitmask):
  record_name = bitmask.name.lower()
  type_name = record_name

  len_cmn = get_len_common_prefix_of_element(bitmask)

  start_s = "-record ({},\n         {{".format(record_name)
  s = ""
  l = 10
  bitmasks[record_name] = {}
  for e in bitmask.entry:
    if e.end_marker:
      continue
    if e.value == 0 or not is_position(e.value):
      continue
    if s:
      s += ",\n" + " " * l
    e_name = atom_repr(e.name[len_cmn:].lstrip('_').lower())
    value = int(math.log(e.value, 2))
    bitmasks[record_name][e_name] = int(value)
    s += "{} = false :: boolean()".format(e_name)

  return '\n' + start_s + s + "}}).\n-type {}() :: #{}{{}}.\n".format(type_name, record_name)


def generate_entry_enum(enum, l0, reverse=False, format="{} => {}"):
  s = ""
  l = l0
  enum_name = enum.name.lower()

  len_cmn = get_len_common_prefix_of_element(enum)

  entry_names = []
  for entry in enum.entry:
    if entry.end_marker:
      continue
    entry_name = entry.name.lower()[len_cmn:].lstrip('_')
    if not entry_name:
      raise ValueError("Erase entry name " + entry.name)
    item = format.format(*(str(entry.value), atom_repr(entry_name))[::reverse*-2+1])
    if len(s) + l + len(item) > 110:
      s += ",\n"
      l = -len(s)
      s += " " * l0
    elif s:
      s += ", "
    s += item
  return s


def generate_enumeration(enum):
  define_name = enum.name.upper()
  type_name = define_name.lower()

  s = "-define ({}_dec,\n         #{{".format(define_name)
  len_repr = 11
  s += "{}}}).\n".format(generate_entry_enum(enum, len_repr))

  s += "-define ({}_enc,\n         #{{".format(define_name)
  s += "{}}}).\n".format(generate_entry_enum(enum, len_repr, reverse=True))

  ts = "-define ({},\n         {{".format(define_name)
  ts += "{}}}).\n".format(generate_entry_enum(enum, len_repr, reverse=True, format="{}"))

  s += ts + "-type {}() :: ?{}.\n".format(type_name, define_name)
  return '\n' + s


def generate_enums(enums):
  enums_repr = ""
  for enum in enums:
    if enum.bitmask:
      enums_repr += generate_bitmask(enum)
    else:
      enums_repr += generate_enumeration(enum)
  return enums_repr


def generate_headers_message(messages):
  messages_repr = ""
  for m in messages:
    start_s = "-record ({}, {{".format(m.name.lower())
    l = len(start_s)
    s = ""
    for f in m.fields:
      if s:
        s += ",\n" + " " * l
      s += "{} :: ".format(atom_repr(f.name.lower()))
      if f.array_length:
        if f.type == "char":
          s += "<<_:{}>>".format(f.array_length)
          continue
        s += '['

      if f.enum:
        s += f.enum.lower()
      else:
        s += f.type
      s += "()"

      if f.array_length:
        s += ']'
    messages_repr += '\n' + start_s + s + "}).\n"
  return messages_repr


def bitmask_mask(field):
  bitmask = [None] * types[field.type].unit
  for key, value in bitmasks[field.enum.lower()].items():
    little_val = (value // 8) * 8 + 7 - (value % 8)
    bitmask[little_val] = key
  match = []
  for bit in bitmask:
    if bit is None:
      if match and isinstance(match[-1], int):
        match[-1] += 1
      else:
        match.append(1)
    else:
      match.append(bit)
  return match


def repr_bitmask_matching(field):
  sa = []
  for element in bitmask_mask(field):
    if isinstance(element, int):
      sa.append("_:{}/binary-unit:1".format(element))
    else:
      sa.append("{}_{}:1/unsigned-integer-unit:1".format(field.name.title(), element.strip("'").title()))
  return sa


def repr_bitmask_record(field):
  return ["{} = {}_{} == 1".format(f, field.name.title(), f.strip("'").title()) for f in bitmasks[field.enum.lower()]]


def generate_crc_extra(message):
  return "crc_extra({}) -> {};\n".format(message.id, message.crc_extra)


def generate_decode(message):
  message_name = message.name.lower()

  start_s = "message({}, <<".format(message.id)
  len_def_s = len(start_s)
  definition_s = ""
  for f in message.ordered_fields:
    t = types[f.type]
    if definition_s:
      definition_s += ",\n" + " " * len_def_s
    if f.enum.lower() in bitmasks:
      definition_s += (",\n" + " " * len_def_s).join(repr_bitmask_matching(f))
    else:
      definition_s += "{}:{}/little-{}{}-unit:{}".format(
        f.name.title(), f.array_length or 1,
        t.signed if not f.array_length else "",
        t.erl_type if not f.array_length else "binary",
        t.unit)
  definition_s = "\n{}{}>>) ->\n".format(start_s, definition_s)

  start_create_record_s = "  #{}{{".format(message_name)
  len_rec_s = len(start_create_record_s)
  record_s = ""
  unpacked_s = ""
  line = ""
  for f in message.ordered_fields:
    if record_s:
      record_s += ",\n"
      line += " " * len_rec_s
    line += "{} = ".format(atom_repr(f.name.lower()))

    f_enum = f.enum.lower()

    if f_enum in bitmasks:
      line += "#{}{{".format(f_enum)
      line += "{}}}".format((",\n" + " " * (len(line))).join(repr_bitmask_record(f)))
    elif f.enum:
      line += "maps:get({}, ?{}_dec)".format(f.name.title(), f.enum.upper())
    elif f.type == 'char':
      line += "trim(" + f.name.title() + ", <<\"\">>)"
    elif f.array_length:
      t = types[f.type]
      l = "  {name}_unpacked = unpack_binary({type}, {size}, {name}),".format(
        name=f.name.title(),
        type=t.erl_type,
        size=t.unit)
      unpacked_s += l + "\n"
      line += f.name.title() + "_unpacked"
    else:
      line += f.name.title()
    record_s += line
    line = ""

  record_s = start_create_record_s + record_s + "};"
  s = "{}{}{}\n".format(definition_s, unpacked_s, record_s)
  return s


def generate_encode(message):
  message_name = message.name.lower()

  start_s = "encode(#{}{{".format(message_name)
  len_s = len(start_s)
  def_s = ""
  for f in message.ordered_fields:
    if def_s:
      def_s += ",\n" + " " * len_s
    f_enum = f.enum.lower()
    if f_enum in bitmasks:
      start_bitmask_s = "{} = #{}{{".format(atom_repr(f.name.lower()), f_enum)
      len_start_bitmask_s = len(start_bitmask_s)
      bitmask_s = ""
      for b in bitmasks[f_enum]:
        if bitmask_s:
          bitmask_s += ",\n" + " " * (len_s + len_start_bitmask_s)
        bitmask_s += "{} = {}_{}".format(b, f.name.title(), b.strip("'").title())
      def_s += "{}{}}}".format(start_bitmask_s, bitmask_s)
    else:
      def_s += "{} = {}".format(atom_repr(f.name.lower()), f.name.title())
  s = "\n{}{}}}) ->\n".format(start_s, def_s)

  for f in message.ordered_fields:
    if f.type == 'char':
      s += "  {0}_encoded = to_string({0}, {1}),\n".format(f.name.title(), f.array_length)
    elif f.array_length:
      t = types[f.type]
      s += "  {name}_packed = pack_binary({type}, {unit}, {name}),\n".format(
        name=f.name.title(), type=t.erl_type, unit=t.unit)
    if f.enum:
      if f.enum.lower() in bitmasks:
        for b in bitmasks[f.enum.lower()]:
          s += "  {0}_{1}_encoded = to_int({0}_{1}),\n".format(f.name.title(), b.strip("'").title())
      else:
        s += "  {}_encoded = maps:get({}, ?{}_enc),\n".format(f.name.title(), f.name.title(), f.enum.upper())

  s += "  {%i, <<" % message.id
  items = []
  for f in message.ordered_fields:
    if f.enum.lower() in bitmasks:
      for element in bitmask_mask(f):
        if isinstance(element, int):
          items.append("0:{}".format(element))
        else:
          items.append("{}_{}_encoded:1".format(f.name.title(), element.strip("'").title()))
    elif f.array_length and f.type != 'char':
      items.append("{name}_packed/binary".format(name=f.name.title()))
    else:
      t = types[f.type]
      items.append("{name}{encoded}:{length}/little-{signed}{erl_type}-unit:{unit}".format(
        name = f.name.title(),
        encoded = "_encoded" if f.enum or f.type == "char" else "",
        length = f.array_length or 1,
        signed = t.signed,
        erl_type = t.erl_type,
        unit = t.unit))

  line = ""
  for i in items:
    if len(line) + len(i) > 110:
      s += line
      s += ",\n    "
      line = ""
    elif line:
      line += ", "
    line += i
  s += line
  s += ">>, %i};\n" % message.crc_extra

  return s


def generate_bitmasks_to_proplist():
  s = "\n% Generated bitmasks to_proplist\n"

  for key in bitmasks:
    s += """
to_proplist(#{bitmask}{{}}=Bitmask) ->
  lists:zip(record_info(fields, {bitmask}), tl(tuple_to_list(Bitmask)));\n""".format(bitmask = key)
  return s

def generate_to_proplists(message):
  message_name = message.name.lower()

  s = """
to_proplist(#{msg_type}{{}}=Msg) ->
  lists:zip(record_info(fields, {msg_type}), tl(tuple_to_list(""".format(msg_type = message_name)

  elements_to_proplist = []
  for f in message.ordered_fields:
    f_enum = f.enum.lower()
    if f_enum in bitmasks:
      f_name = f.name.lower()
      elements_to_proplist.append("{element}=to_proplist(Msg#{msg_type}.{element})".format(
        element=f_name, msg_type=message_name))

  if elements_to_proplist:
    s += "Msg#{msg_type}{{\n    {elements}}}".format(
      elements=",\n    ".join(elements_to_proplist),
      msg_type=message_name)
  else:
    s += "Msg"

  s += ")));\n"

  return s


def generate(directory, xml):
  mavparse.mkdir_p(directory)

  print("\nmavgen_erlang...")
  print("generate to {}\n".format(directory))

  hrl_path = os.path.join(directory, "mavlink.hrl")
  erl_path = os.path.join(directory, "mavlink.erl")
  hrl_out = open(hrl_path, "w")
  erl_out = open(erl_path, "w")

  hrl_out.write(hrl_header())
  erl_out.write(erl_header())

  for x in xml[::-1]:
    hrl_out.write("\n% Generated from {}\n".format(x.basename))
    print("Generate enums {}".format(x.basename))
    hrl_out.write(generate_enums(x.enum))

  for x in xml[::-1]:
    hrl_out.write("\n% Generated from {}\n".format(x.basename))
    print("Generate headers message {}".format(x.basename))
    hrl_out.write(generate_headers_message(x.message))
  hrl_out.close()

  for x in xml[::-1]:
    erl_out.write("\n% Generated from {}\n".format(x.basename))
    print("Generate crc_extra {}".format(x.basename))
    for m in x.message:
      erl_out.write(generate_crc_extra(m))
  erl_out.write(crc_extra_footer())

  for x in xml[::-1]:
    erl_out.write("\n% Generated from {}\n".format(x.basename))
    print("Generate decodes {}".format(x.basename))
    for m in x.message:
      erl_out.write(generate_decode(m))
  erl_out.write(decode_footer())

  for x in xml[::-1]:
    erl_out.write("\n% Generated from {}\n".format(x.basename))
    print("Generate encodes {}".format(x.basename))
    for m in x.message:
      erl_out.write(generate_encode(m))
  erl_out.write(encode_footer())

  erl_out.write(generate_bitmasks_to_proplist())

  for x in xml[::-1]:
    erl_out.write("\n% Generated from {}\n".format(x.basename))
    print("Generate to_proplists {}".format(x.basename))
    for m in x.message:
      erl_out.write(generate_to_proplists(m))
  erl_out.write(to_proplists_footer())

  erl_out.close()

  print("\nmavgen_erlang OK")
